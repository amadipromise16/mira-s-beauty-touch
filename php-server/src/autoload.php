<?php

declare(strict_types=1);

/**
 * PSR-4 Compatible Autoloader for Mira's Beauty Touch PHP Backend.
 * Ensures the application runs out of the box with zero external dependencies.
 */

spl_autoload_register(function (string $class): void {
    $prefix = 'App\\';
    $baseDir = __DIR__ . '/';

    $len = strlen($prefix);
    if (strncmp($prefix, $class, $len) !== 0) {
        return;
    }

    $relativeClass = substr($class, $len);
    $file = $baseDir . str_replace('\\', '/', $relativeClass) . '.php';

    if (file_exists($file)) {
        require_once $file;
    }
});

